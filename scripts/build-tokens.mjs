// Reads design-tokens/tokens.json, checks colour contrast, and writes src/styles/tokens.css.
// Run: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../design-tokens/tokens.json', import.meta.url), 'utf8'));

// WCAG 2.1 contrast ratio
const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

// [foreground, background, minimum ratio]
const pairs = [
  ['text', 'surface', 4.5], ['text', 'surface-raised', 4.5], ['text-muted', 'surface', 4.5],
  ['on-accent', 'accent', 4.5], ['success-text', 'success-bg', 4.5],
  ['danger-text', 'danger-bg', 4.5], ['neutral-text', 'neutral-bg', 4.5],
  ['accent', 'surface', 3], ['focus', 'surface', 3], ['border', 'surface', 1.2], ['border-strong', 'surface', 3],
];
let failed = false;
for (const mode of ['light', 'dark']) {
  for (const [fg, bg, min] of pairs) {
    const r = ratio(t.color[mode][fg], t.color[mode][bg]);
    const ok = r >= min;
    if (!ok) failed = true;
    console.log(`${ok ? 'pass' : 'FAIL'} ${mode.padEnd(5)} ${fg} on ${bg}: ${r.toFixed(2)} (needs ${min})`);
  }
}

const block = (sel, obj, prefix) =>
  `${sel} {\n${Object.entries(obj).map(([k, v]) => `  --${prefix}-${k}: ${v};`).join('\n')}\n}\n`;

let css = '/* Generated by scripts/build-tokens.mjs. Do not edit by hand. */\n';
css += block(':root', t.color.light, 'color');
css += block('[data-theme="dark"]', t.color.dark, 'color');
css += `:root {\n`;
for (const [k, v] of Object.entries(t.space)) css += `  --space-${k}: ${v};\n`;
for (const [k, v] of Object.entries(t.radius)) css += `  --radius-${k}: ${v};\n`;
for (const [k, v] of Object.entries(t.font.size)) css += `  --font-size-${k}: ${v};\n`;
for (const [k, v] of Object.entries(t.font.line)) css += `  --line-${k}: ${v};\n`;
css += `  --font-family: ${t.font.family};\n  --size-control: ${t.size.control};\n  --size-dot: ${t.size.dot};\n}\n`;

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);
console.log(failed ? '\nSome pairs fail contrast. Fix tokens.json.' : '\nAll contrast checks passed. Wrote src/styles/tokens.css');
process.exit(failed ? 1 : 0);
